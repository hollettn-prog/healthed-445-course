from pathlib import Path
from zipfile import ZipFile, ZIP_DEFLATED
from xml.etree import ElementTree as ET
import json, hashlib, html, re, sys
ROOT=Path(__file__).resolve().parent.parent
OUT=ROOT/'dist'/'HEALTHED-445-sandbox.imscc'
CC='http://www.imsglobal.org/xsd/imsccv1p1/imscp_v1p1'
CV='http://canvas.instructure.com/xsd/cccv1p0'
ET.register_namespace('',CC)
def e(parent,name,text=None,ns=CC,**attrs):
    x=ET.SubElement(parent,'{%s}%s'%(ns,name),attrs)
    if text is not None:x.text=str(text)
    return x
def sid(s):return 'g'+hashlib.sha256(s.encode()).hexdigest()[:24]
def slug(s):return re.sub(r'[^a-z0-9]+','-',s.lower()).strip('-')
def xml(x):return ET.tostring(x,encoding='utf-8',xml_declaration=True)
def main():
    data=json.loads((ROOT/'course-map.json').read_text())
    modules=data['modules']; entries=[]; errors=[]
    for m in modules:
        for p in m['pages']:
            path=ROOT/p['file']
            if not path.is_file():errors.append(p['file'])
            else:entries.append((m,p,path))
    if errors:sys.exit('Missing files:\n'+'\n'.join(errors))
    if not entries:sys.exit('No approved pages in course-map.json')
    manifest=ET.Element('{%s}manifest'%CC,identifier=sid('h445'))
    md=e(manifest,'metadata');e(md,'schema','IMS Common Cartridge');e(md,'schemaversion','1.1.0')
    orgs=e(manifest,'organizations');org=e(orgs,'organization',identifier='org1',structure='rooted-hierarchy');wrapper=e(org,'item',identifier='LearningModules');e(wrapper,'title','Learning Modules')
    resources=e(manifest,'resources');module_root=ET.Element('{%s}modules'%CV)
    payload={};count=0
    for m in modules:
        n=m['number'];mid=sid('module:'+str(n));om=e(wrapper,'item',identifier=mid);e(om,'title',m['title'])
        cm=e(module_root,'module',ns=CV,identifier=mid)
        e(cm,'title',m['title'],ns=CV);e(cm,'workflow_state','unpublished',ns=CV);e(cm,'position',n,ns=CV)
        items=e(cm,'items',ns=CV)
        pages=m['pages']
        for idx,p in enumerate(pages):
            source=ROOT/p['file']; title=p['title']; pid=sid(p['file']);iid=sid('item:'+p['file']);page_slug=slug(title)
            href='wiki_content/'+page_slug+'.html'
            resource=e(resources,'resource',identifier=pid,type='webcontent',href=href)
            e(resource,'file',href=href)
            oi=e(om,'item',identifier=iid,identifierref=pid);e(oi,'title',title)
            ci=e(items,'item',ns=CV,identifier=iid)
            for k,v in [('content_type','WikiPage'),('workflow_state','active'),('title',title),('identifierref',pid),('position',idx+1),('indent',0)]:e(ci,k,v,ns=CV)
            body=source.read_text(encoding='utf-8')
            # Internal Canvas links are relative to the destination course, never the GitHub URL.
            prev=pages[idx-1] if idx else None
            nxt=pages[idx+1] if idx+1<len(pages) else None
            nav=['<nav aria-label="Page navigation" style="border-top:1px solid #E9E9EE;margin-top:28px;padding-top:18px">']
            if prev:nav.append('<p><a style="color:#4F2D7F;font-weight:bold" href="/courses/{course_id}/pages/'+slug(prev['title'])+'">Previous: '+html.escape(prev['title'])+'</a></p>')
            if nxt:nav.append('<p style="font-size:14px;font-weight:bold;color:#4F2D7F;margin-bottom:4px">UP NEXT</p><p><a style="color:#4F2D7F;font-weight:bold" href="/courses/{course_id}/pages/'+slug(nxt['title'])+'">'+html.escape(nxt['title'])+' &rarr;</a></p>')
            nav.append('</nav>')
            body=body.replace('<!-- NAVIGATION: generated by scripts/build_canvas_package.py -->',''.join(nav))
            header='<!DOCTYPE html><html><head><meta charset="utf-8"><title>'+html.escape(title)+'</title><meta name="identifier" content="'+pid+'"><meta name="editing_roles" content="teachers"><meta name="workflow_state" content="unpublished"></head><body>'
            payload[href]=header+body+'</body></html>';count+=1
    course=ET.Element('{%s}course'%CV,identifier=sid('h445-course'))
    e(course,'title','HEALTHED 445 Sandbox Content',ns=CV);e(course,'course_code','HEALTHED 445',ns=CV)
    settings={'course_settings/course_settings.xml':xml(course),'course_settings/module_meta.xml':xml(module_root)}
    bundle=e(resources,'resource',identifier=sid('settings'),type='associatedcontent/imscc_xmlv1p1/learning-application-resource',href='course_settings/course_settings.xml')
    for name in settings:e(bundle,'file',href=name)
    OUT.parent.mkdir(parents=True,exist_ok=True)
    with ZipFile(OUT,'w',ZIP_DEFLATED) as z:
        z.writestr('imsmanifest.xml',xml(manifest))
        for k,v in payload.items():z.writestr(k,v)
        for k,v in settings.items():z.writestr(k,v)
    print('Built',OUT,'with',count,'pages and',len(modules),'module(s)')
    print('Check navigation links in Canvas after importing; Canvas may rewrite page slugs.')
if __name__=='__main__':main()
